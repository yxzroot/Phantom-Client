package keystrokesmod.client.module.modules.render.swordglow;

final class SwordEnergyShaders {
    static final String VERTEX="#version 120\n"
        +"uniform vec3 axis;uniform vec2 limits;uniform vec2 pixelOffset;varying vec2 atlasUV;varying vec2 uv;varying float height;"
        +"void main(){atlasUV=gl_MultiTexCoord0.xy;height=clamp((dot(gl_Vertex.xyz,axis)-limits.x)/limits.y,0.0,1.0);"
        +"uv=(gl_TextureMatrix[0]*vec4(gl_Vertex.x,gl_Vertex.y,0,1)).xy;"
        +"gl_Position=gl_ModelViewProjectionMatrix*gl_Vertex;gl_Position.xy+=pixelOffset*gl_Position.w;}";
    static final String FRAGMENT="#version 120\n"
        +"uniform sampler2D energy;uniform sampler2D atlas;uniform vec3 colorA;uniform vec3 colorB;uniform float clock;uniform float amount;uniform float width;"
        +"uniform float bright;uniform float block;uniform float charge;uniform float burst;uniform float hit;uniform float equip;uniform int style;uniform int oldStyle;"
        +"uniform float swingEnergy;uniform float swingSweep;"
        +"uniform int secondary;uniform int oldSecondary;uniform float secondaryMix;uniform float transition;uniform int mode;uniform int layer;uniform int colorMode;varying vec2 atlasUV;varying vec2 uv;varying float height;"
        +"vec3 rainbow(float h){return clamp(abs(fract(h+vec3(0,.6667,.3333))*6.0-3.0)-1.0,0.0,1.0);}"
        +"float band(float center,float w){return exp(-pow((height-center)/max(.04,w),2.0));}"
        +"float effect(int s,float n){float t=clock;float v=height;float b=0.0;"
        +"if(s==0)b=band(fract(t*.32+float(layer)*.34)*1.5-.25,width)+texture2D(energy,uv*.55).g*.25;"
        +"if(s==1){float age=mod(t,3.1);b=exp(-pow((v-(age/.9*1.5-.25)+uv.x*.08)/max(.035,width*.35),2.0))*(1.0-smoothstep(.85,1.0,age));}"
        +"if(s==2)b=(.36+.42*(.5+.5*sin(t*2.4)))*(.5+n*.55);"
        +"if(s==3)b=pow(n,1.8)*(1.3-v*.45)*(.75+.25*sin(t*9.0+v*16.0));"
        +"if(s==4){float tick=floor(t/.115);float flash=step(.80,fract(sin(tick*17.3)*43758.5));float arc=sin(v*23.0+tick)*.10+sin(v*57.0-tick)*.04;"
        +"b=flash*exp(-pow((fract(uv.x*.17)-.5+arc)/.045,2.0))*(1.0-fract(t/.115));}"
        +"if(s==5){float star=texture2D(energy,uv*.65+vec2(t*.012,-t*.018)).b;b=pow(star,3.0)*(.65+.35*sin(t*2.0+v*20.0))+.06*n;}"
        +"if(s==6)b=(.25+texture2D(energy,uv*vec2(.28,1.1)+vec2(t*.025,0)).g*.8)*(.6+.4*n)*(.8+.2*sin(v*9.0-t*.4));"
        +"if(s==7)b=(.36+texture2D(energy,uv*.6).g*.5)*(.7+n*.3);"
        +"if(s==8)b=(.10+charge*.65)*(.6+n*.4)+burst*(.4+band(fract(t*1.8),.35));"
        +"if(s==9){float gate=step(.76,fract(sin(floor(t*13.0)*13.3)*4375.8));b=.13+gate*(.5+step(.55,fract(v*8.0+t*5.0))*.6);}"
        +"if(s==10)b=pow(abs(n-.5)*2.0,1.4)*(.45+.25*sin(t*1.7+v*4.0));return max(0.0,b);}"
        +"void main(){vec4 blade=texture2D(atlas,atlasUV);if(blade.a<.1)discard;"
        +"vec3 col=mix(colorA,colorB,smoothstep(.05,1.0,height));"
        +"float rainbowMix=style==7?transition:oldStyle==7?1.0-transition:0.0;if(colorMode==2)rainbowMix=1.0;col=mix(col,rainbow(height*.7-clock*.16),rainbowMix);"
        +"float auroraMix=style==6?transition:oldStyle==6?1.0-transition:0.0;col=mix(col,mix(vec3(.13,1,.58),vec3(.68,.21,1),height),.48*auroraMix);"
        +"col=mix(col,vec3(.46,.82,1),block*.48);"
        +"if(mode==1){gl_FragColor=vec4(0);return;}if(mode==2){gl_FragColor=vec4(col,amount);return;}"
        +"float n=texture2D(energy,uv*.6+vec2(clock*.025,-clock*.09)).r;"
        +"float b=mix(effect(oldStyle,n),effect(style,n),transition);if(secondary>=0)b+=effect(secondary,n)*.28*secondaryMix;if(oldSecondary>=0)b+=effect(oldSecondary,n)*.28*(1.0-secondaryMix);"
        +"float sweep=(1.0-step(.999,equip))*band(equip*1.5-.25,.17);b+=sweep*.65+hit*.7+block*.12*(.5+.5*sin(clock*3.0));"
        +"b+=swingEnergy*(.12+.55*band(swingSweep*1.5-.25,.16));"
        +"if(mode==3){gl_FragColor=vec4(mix(vec3(1),vec3(.72+.22*n),amount*.6),1);return;}"
        +"float lum=dot(blade.rgb,vec3(.2126,.7152,.0722));float sat=max(blade.r,max(blade.g,blade.b))-min(blade.r,min(blade.g,blade.b));"
        +"float contrast=1.0+lum*.38+sat*.42;float hot=smoothstep(.5,1.1,b)*.52;"
        +"vec3 energyColor=mix(col,col*.35+vec3(.85),hot)*mix(1.12,.72,height);"
        +"if(style==9){float gate=step(.76,fract(sin(floor(clock*13.0)*13.3)*4375.8))*transition;float slice=sin(floor(height*9.0)*11.3+floor(clock*13.0))*.08;"
        +"vec2 p=uv+vec2(slice,0);vec3 split=vec3(texture2D(energy,p+vec2(.045,0)).g,texture2D(energy,p).g,texture2D(energy,p-vec2(.045,0)).g);energyColor=mix(energyColor,split*1.7,gate*.60);}"
        +"gl_FragColor=vec4(energyColor*bright*contrast,clamp(b*amount,0.0,.8));}";
}
